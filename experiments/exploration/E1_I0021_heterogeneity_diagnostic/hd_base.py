# --------------------------------------------------------------------------- prior-only references
def _expanding_prior_mean(f, valcol, keys=("season", "player_id")):
    """Expanding mean of the player's own STRICTLY PRIOR same-season values.

    .shift(1) BEFORE .expanding(), exactly as psd_base does it.  Row i sees rows 0..i-1 of its own
    (season, player) group and nothing else.
    """
    return f.groupby(list(keys), sort=False)[valcol].transform(
        lambda x: x.shift(1).expanding().mean())


def _expanding_prior_ratio(f, numcol, dencol, keys=("season", "player_id")):
    g = f.groupby(list(keys), sort=False)
    num = g[numcol].transform(lambda x: x.shift(1).expanding().sum())
    den = g[dencol].transform(lambda x: x.shift(1).expanding().sum())
    return num / den.replace(0.0, np.nan)


def _league_prior_mean(f, valcol, datecol="gdate"):
    fs = f.sort_values(["season", datecol], kind="stable")
    cum = fs.groupby("season", sort=False)[valcol].transform(
        lambda x: x.shift(1).expanding().mean())
    return cum.reindex(f.index)


def build_floor_references(f, floor, datecol="gdate", mincol="y_minutes", verbose=False):
    """FLOOR-AWARE rebuild of every prior-only reference, for a given realised-minutes floor.

    THIS IS THE HONEST CONTROL the directive demands.  Two reference families are produced:

      FROZEN   -- D081's published references (`ref_*`, `refA_*`, `refB_*`), built over ALL prior
                  games, simply SUBSET to the rows that clear the floor.  Model and reference face
                  the SAME rows, but the reference gets none of the denoising benefit.

      REFIT    -- the SAME construction, but the expanding prior windows are computed over the
                  player's prior games THAT THEMSELVES CLEARED THE FLOOR.  The reference now enjoys
                  exactly the same denoising the response enjoys.  A skill gain that survives HERE
                  is not the mechanical artefact of dropping noisy rows.

    Strictly prior in both families: shift(1) before expanding, inside (season, player_id), and the
    cold fallback is an expanding league mean over games strictly EARLIER IN THE SAME SEASON.
    Nothing in either family reads a game on or after the row's own date.
    """
    f = f.copy()
    keep = f[mincol] >= float(floor)
    sub = f.loc[keep].copy()
    if len(sub) == 0:
        return sub

    # rates on the retained rows
    sub["r_ppm"] = sub["y_pts"] / sub["y_minutes"]
    sub["r_fpm"] = sub["y_fga"] / sub["y_minutes"]
    sub["r_ppf"] = np.where(sub["y_fga"] > 0, sub["y_pts"] / sub["y_fga"].replace(0, np.nan), np.nan)

    # ---- REFIT level references (prior games that themselves cleared the floor) ----
    for t in ["pts", "minutes", "fga"]:
        prior = _expanding_prior_mean(sub, "y_" + t)
        lg = _league_prior_mean(sub, "y_" + t, datecol)
        sub["refF_" + t] = prior.fillna(lg).fillna(sub["y_" + t].mean())

    # ---- REFIT rate references ----
    spec = {"ppm": ("y_pts", "y_minutes"), "fpm": ("y_fga", "y_minutes"), "ppf": ("y_pts", "y_fga")}
    for rt, (num, den) in spec.items():
        col = "r_" + rt
        a = _expanding_prior_mean(sub, col)
        b = _expanding_prior_ratio(sub, num, den)
        lg = _league_prior_mean(sub, col, datecol)
        sub["refFA_" + rt] = a.fillna(lg).fillna(sub[col].mean())
        sub["refFB_" + rt] = b.fillna(lg).fillna(sub[col].mean())

    if verbose:
        print("    floor=%s  n=%d  refit references rebuilt on floor-clearing prior games only"
              % (floor, len(sub)))
    return sub


# --------------------------------------------------------------------------- skill
def mae(y, yhat):
    y = np.asarray(y, float)
    yhat = np.asarray(yhat, float)
    m = np.isfinite(y) & np.isfinite(yhat)
    return float(np.mean(np.abs(y[m] - yhat[m])))


def skill(y, yhat_model, yhat_ref):
    """1 - MAE_model/MAE_ref, both on the SAME finite rows."""
    y = np.asarray(y, float)
    m = np.asarray(yhat_model, float)
    r = np.asarray(yhat_ref, float)
    ok = np.isfinite(y) & np.isfinite(m) & np.isfinite(r)
    mm = float(np.mean(np.abs(y[ok] - m[ok])))
    mr = float(np.mean(np.abs(y[ok] - r[ok])))
    return float(1.0 - mm / mr), mm, mr, int(ok.sum())


# --------------------------------------------------------------------------- per-player OLS
def per_player_slopes(df, xcol, ycol, pcol="player_id", min_games=8, demean=True):
    """Simple per-player OLS slope of ycol on xcol, one slope per player.

    Returns a DataFrame: player_id, n, beta, se, sd_x, sd_y.  Players with fewer than `min_games`
    rows, or with zero within-player variance in x, are dropped and counted by the caller.

    `demean=True` centres x and y INSIDE the player, which makes the slope a purely WITHIN-player
    quantity: it cannot be contaminated by between-player level differences, which is exactly the
    confound that would otherwise manufacture spread.
    """
    x = pd.to_numeric(df[xcol], errors="coerce").to_numpy(float)
    y = pd.to_numeric(df[ycol], errors="coerce").to_numpy(float)
    p = df[pcol].to_numpy()
    ok = np.isfinite(x) & np.isfinite(y)
    x, y, p = x[ok], y[ok], p[ok]
    order = np.argsort(p, kind="stable")
    x, y, p = x[order], y[order], p[order]
    uq, start = np.unique(p, return_index=True)
    ends = np.append(start[1:], len(p))
    rows = []
    for pid, a, b in zip(uq, start, ends):
        n = b - a
        if n < min_games:
            continue
        xi, yi = x[a:b], y[a:b]
        if demean:
            xi = xi - xi.mean()
            yi = yi - yi.mean()
        sxx = float((xi * xi).sum())
        if sxx <= 0:
            continue
        beta = float((xi * yi).sum() / sxx)
        resid = yi - beta * xi
        dof = n - (2 if demean else 1)
        if dof <= 0:
            continue
        s2 = float((resid * resid).sum() / dof)
        se = float(np.sqrt(s2 / sxx)) if sxx > 0 else np.nan
        rows.append(dict(player_id=pid, n=int(n), beta=beta, se=se,
                         sd_x=float(np.std(x[a:b], ddof=1)) if n > 1 else np.nan,
                         sd_y=float(np.std(y[a:b], ddof=1)) if n > 1 else np.nan))
    return pd.DataFrame(rows)


def group_slopes_fast(x, y, gcode, ng, min_games=8):
    """VECTORISED per-group within-demeaned OLS slope + its standard error.

    Identical arithmetic to `per_player_slopes(demean=True)` -- asserted equal in s02 before any
    null is drawn -- but implemented with bincount so 2000 permutation draws are affordable.

    Returns (beta, se, n, valid_mask) as arrays of length ng.
    """
    n = np.bincount(gcode, minlength=ng).astype(float)
    sx = np.bincount(gcode, weights=x, minlength=ng)
    sy = np.bincount(gcode, weights=y, minlength=ng)
    with np.errstate(invalid="ignore", divide="ignore"):
        mx = sx / n
        my = sy / n
    xc = x - mx[gcode]
    yc = y - my[gcode]
    sxx = np.bincount(gcode, weights=xc * xc, minlength=ng)
    sxy = np.bincount(gcode, weights=xc * yc, minlength=ng)
    with np.errstate(invalid="ignore", divide="ignore"):
        beta = np.where(sxx > 0, sxy / np.where(sxx > 0, sxx, 1.0), np.nan)
    resid = yc - np.where(np.isfinite(beta), beta, 0.0)[gcode] * xc
    sse = np.bincount(gcode, weights=resid * resid, minlength=ng)
    dof = n - 2.0
    with np.errstate(invalid="ignore", divide="ignore"):
        s2 = np.where(dof > 0, sse / np.where(dof > 0, dof, 1.0), np.nan)
        se = np.sqrt(np.where(sxx > 0, s2 / np.where(sxx > 0, sxx, 1.0), np.nan))
    valid = (n >= min_games) & (sxx > 0) & np.isfinite(beta) & np.isfinite(se) & (dof > 0)
    return beta, se, n, valid


def spread_from_slopes(beta, se, valid, weighted=True):
    """SD of the per-group slopes over the valid groups.  Precision-weighted or plain."""
    b = beta[valid]
    if len(b) < 3:
        return float("nan")
    if not weighted:
        return float(np.std(b, ddof=1))
    w = 1.0 / np.maximum(se[valid] ** 2, 1e-300)
    w = np.where(np.isfinite(w), w, 0.0)
    if w.sum() <= 0:
        return float(np.std(b, ddof=1))
    mu = float((w * b).sum() / w.sum())
    return float(np.sqrt(np.average((b - mu) ** 2, weights=w)))


def permute_within_groups(x, gcode_sorted_rows, rng):
    """Shuffle x INSIDE each group.  Rows MUST already be sorted by gcode.

    Preserves every group's SAMPLE SIZE and its MARGINAL DISTRIBUTION of x exactly; destroys only
    the within-group alignment of x to y.  This is the null the directive specifies.
    """
    r = rng.random(len(x))
    order = np.lexsort((r, gcode_sorted_rows))
    return x[order]


def cyclic_shift_within_groups(x, group_starts, group_ns, rng):
    """Rotate each group's x series by a random offset.  Rows MUST be sorted by group, then DATE.

    THE POINT.  Several of the preregistered regressors are RUNNING MEANS of the player's own
    history (their expanding prior efficiency, their expanding prior usage).  Such a series is
    strongly autocorrelated and trends inside a season.  A plain within-player SHUFFLE destroys that
    autocorrelation, so if the response also carries a within-season trend, the shuffle null is too
    narrow and a shared time trend can masquerade as per-player response heterogeneity.

    A CYCLIC SHIFT preserves each player's marginal distribution AND its serial correlation
    structure exactly, and destroys only the alignment to the response.  An excess spread that
    survives this null is not a trend artefact.
    """
    out = np.empty_like(x)
    for a, n in zip(group_starts, group_ns):
        if n <= 1:
            out[a:a + n] = x[a:a + n]
            continue
        k = int(rng.integers(0, n))
        out[a:a + n] = np.roll(x[a:a + n], k)
    return out


def slope_spread_stat(df, xcol, ycol, pcol="player_id", min_games=8, weighted=True):
    """THE STEP-2 STATISTIC: the SD of per-player slopes.

    `weighted=True` weights each player's slope by 1/se^2 relative to the precision-weighted mean,
    which is the natural scale-free version; `weighted=False` is the plain unweighted SD.  Both are
    reported.  The statistic is computed by the IDENTICAL code path on the real frame and on every
    permuted draw, so any in-sample optimism is present in the null too.
    """
    s = per_player_slopes(df, xcol, ycol, pcol=pcol, min_games=min_games)
    if len(s) < 3:
        return float("nan")
    b = s["beta"].to_numpy(float)
    if not weighted:
        return float(np.std(b, ddof=1))
    w = 1.0 / np.maximum(s["se"].to_numpy(float) ** 2, 1e-300)
    w = np.where(np.isfinite(w), w, 0.0)
    if w.sum() <= 0:
        return float(np.std(b, ddof=1))
    mu = float((w * b).sum() / w.sum())
    return float(np.sqrt(np.average((b - mu) ** 2, weights=w)))
