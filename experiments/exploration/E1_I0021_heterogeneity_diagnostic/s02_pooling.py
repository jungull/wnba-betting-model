    # --------------------------------------------------------------- noop placebo (constraint 8)
    hb.hdr("noop_placebo -- is the control vacuous?")
    s = floor_subset(m, pr.HEADLINE_FLOOR)
    s, _ = complete_case(s)
    s = s.sort_values(["player_id", "season", "game_date"]).reset_index(drop=True)

    def stat_identity(df):
        return hb.slope_spread_stat(df, "refA_ppm_floor", "y_ppm_floor",
                                    min_games=pr.MIN_GAMES_PER_PLAYER, weighted=True)

    npl = sk.noop_placebo(stat_identity, s, 25, transform=None, verbose=True)
    P("  IDENTITY transform: real=%.8g sd=%.3e distinct=%d -> %s"
      % (npl["real"], npl["sd"], npl["n_distinct_draw_values"], npl["verdict"]))

    def transform_relabel_player(df, rng):
        """THE DEFECTIVE PLACEBO, RUN DELIBERATELY: relabel the player key, refit per-player slopes.

        This is the heterogeneity-shaped version of the trap `noop_placebo` exists to catch, and it
        is the control an analyst would most naturally reach for ("shuffle the player labels and see
        if the spread shrinks").  Relabelling player ids is a BIJECTION ON WHOLE GROUPS: every
        player's row set travels intact to the new label, so the multiset of per-player slopes -- and
        therefore their spread -- is EXACTLY unchanged.  It is expected to be confirmed as a no-op,
        and confirming it is the point: it demonstrates on this screen's own data why the null had
        to permute x INSIDE each player rather than permute the player key.
        """
        d = df.copy()
        u = d["player_id"].unique()
        mp = dict(zip(u, rng.permutation(u)))
        d["player_id"] = d["player_id"].map(mp)
        return d.sort_values(["player_id"]).reset_index(drop=True)

    npl2 = sk.noop_placebo(stat_identity, s, 25, transform=transform_relabel_player, verbose=True)
    P("  RELABEL-PLAYER transform: real=%.8g sd=%.3e distinct=%d -> %s"
      % (npl2["real"], npl2["sd"], npl2["n_distinct_draw_values"], npl2["verdict"]))

