"""
s02 -- STEP 2: THE POOLING DIAGNOSTIC.  THE CENTREPIECE.

THE QUESTION.  Under a genuine null, per-player coefficients scatter around zero with a spread
ENTIRELY EXPLAINED BY SAMPLING NOISE.  If the observed spread of per-player coefficients is WIDER
than the null predicts, real heterogeneous signal exists even though the pooled mean is zero -- the
program's nulls would then be a Type II error by construction rather than by mistake.  If it is not
wider, the heterogeneity hypothesis is closed properly rather than by assumption.  BOTH ANSWERS ARE
VALUABLE AND NEITHER IS STRAINED FOR.

THE STATISTIC.  sd of the per-player within-demeaned OLS slopes, over players with >= 8 retained
games.  Reported precision-weighted and unweighted.  Computed by the IDENTICAL code path on the
real frame and on every permuted draw.

WHY IN-SAMPLE FITTING IS ADMISSIBLE HERE AND NOWHERE ELSE (trap 4).  Each player's slope is fitted
on that player's own games.  Applying such a slope to those same games would be meaningless, and
this script never does that -- the slope is used ONLY as an input to a DISPERSION statistic whose
null is generated by running the same in-sample fit on permuted data.  Whatever in-sample optimism
inflates the observed spread inflates every null draw identically, so it cancels.  Step 4 (single
player prediction) is strictly walk-forward instead.

THREE NULLS, ALL REPORTED (constraint 6 -- correct-level nulls, nine confirmations in this program):
  N1 WITHIN-PLAYER (headline, the null the directive specifies).  Each player's own games are
     shuffled.  Preserves that player's sample size and marginal distribution of x exactly;
     destroys ONLY the alignment of x to y inside the player.
  N2 ROW-LEVEL (contrast only, KNOWN ANTICONSERVATIVE).  Global row shuffle. Reported alongside so
     the inflation is visible, never used for a verdict.
  N3 TEAM-GAME BLOCK (opponent-level x only).  x is an opponent-team aggregate: every player on a
     team shares one value on a night, and their residuals share a team-night shock.  N1 destroys
     that co-occurrence and could therefore be too narrow.  N3 permutes WHOLE TEAM-GAME BLOCKS
     within season, preserving the co-occurrence.  It changes each player's marginal x, which is
     why it is a robustness check and not the headline.

ANALYTIC CROSS-CHECK.  Alongside the permutation, the classical decomposition is reported:
observed var(beta) vs mean(se^2).  If observed variance is no larger than the mean squared standard
error, sampling noise alone explains the spread and no permutation is needed to see it.
"""
