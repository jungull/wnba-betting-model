"""
U13_MONITORING_INTERFACE -- render every fixture and write the auditable views.

PRODUCT SCAFFOLD built against fixtures. Carries no scientific claim and must not imply a model
has been promoted.

Writes:
  MONITOR_VIEWS.md          -- the rendered panel for every fixture, as an operator would see it
  MONITOR_EVALUATIONS.json  -- the machine-readable evaluation of every fixture

Run:  python build_views.py
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from monitor_state import evaluate            # noqa: E402
from render_monitor import render_text        # noqa: E402

FIXTURES = os.path.join(HERE, "fixtures")
EPISTEMIC = ("PRODUCT SCAFFOLD built against fixtures. Carries no scientific claim and must not "
             "imply a model has been promoted.")


def load_fixtures():
    out = []
    for name in sorted(os.listdir(FIXTURES)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(FIXTURES, name), encoding="utf-8") as fh:
            out.append((name[:-5], json.load(fh)))
    return out


def main():
    fixtures = load_fixtures()
    evaluations = {}
    md = ["# U13_MONITORING_INTERFACE — rendered monitor views",
          "",
          f"> {EPISTEMIC}",
          "",
          "Generated by `build_views.py` from the fixtures in `fixtures/`. Every panel below is "
          "the literal output of `render_monitor.render_text(monitor_state.evaluate(...))` at the "
          "fixture's declared evaluation clock. Nothing here is live and nothing here is a model "
          "output.",
          ""]
    for name, fx in fixtures:
        ev = evaluate(fx.get("snapshot"), fx.get("evaluated_at_utc"))
        evaluations[name] = ev
        md.append(f"## `{name}`")
        md.append("")
        md.append(fx.get("purpose", ""))
        md.append("")
        md.append(f"Clock: `{fx.get('evaluated_at_utc')}` · serving: **{ev['serving']}** · "
                  f"projections shown: {ev['counters']['n_projections_shown']}"
                  f"/{ev['counters']['n_projections']} · alerts: {ev['counters']['n_alerts']}")
        md.append("")
        md.append("```")
        md.append(render_text(ev))
        md.append("```")
        md.append("")

    with open(os.path.join(HERE, "MONITOR_VIEWS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(md))
    with open(os.path.join(HERE, "MONITOR_EVALUATIONS.json"), "w", encoding="utf-8",
              newline="\n") as fh:
        json.dump({"schema": "player_program/monitor_evaluation_set/1",
                   "epistemic_status": EPISTEMIC,
                   "evaluations": evaluations}, fh, indent=2)
        fh.write("\n")

    for name, ev in evaluations.items():
        c = ev["counters"]
        print(f"{name:26s} serving={ev['serving']:11s} shown={c['n_projections_shown']}"
              f"/{c['n_projections']} alerts={c['n_alerts']} "
              f"(crit={c['n_alerts_critical']}, warn={c['n_alerts_warning']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
